CREATE TABLE servicio_veterinario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(40) NOT NULL,
    nombre VARCHAR(100) NOT NULL,
    tipo VARCHAR(20) NOT NULL,
    valor_base NUMERIC(14, 0) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_servicio_veterinario_codigo UNIQUE (codigo),
    CONSTRAINT ck_servicio_veterinario_tipo CHECK (tipo IN ('CONSULTA', 'PROCEDIMIENTO')),
    CONSTRAINT ck_servicio_veterinario_valor_positivo CHECK (valor_base > 0)
);

CREATE TABLE beneficio_plan (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id BIGINT NOT NULL,
    servicio_id BIGINT NOT NULL,
    porcentaje_descuento INTEGER NOT NULL,
    CONSTRAINT fk_beneficio_plan_plan
        FOREIGN KEY (plan_id) REFERENCES plan_afiliacion (id) ON DELETE RESTRICT,
    CONSTRAINT fk_beneficio_plan_servicio
        FOREIGN KEY (servicio_id) REFERENCES servicio_veterinario (id) ON DELETE RESTRICT,
    CONSTRAINT uk_beneficio_plan_servicio UNIQUE (plan_id, servicio_id),
    CONSTRAINT ck_beneficio_plan_porcentaje CHECK (porcentaje_descuento BETWEEN 0 AND 100)
);

-- Plan vigente de cada afiliado y mascotas cubiertas por ese plan.
CREATE TABLE afiliacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    afiliado_id BIGINT NOT NULL,
    plan_id BIGINT NOT NULL,
    fecha_inicio DATE NOT NULL,
    CONSTRAINT fk_afiliacion_afiliado
        FOREIGN KEY (afiliado_id) REFERENCES afiliado (id) ON DELETE RESTRICT,
    CONSTRAINT fk_afiliacion_plan
        FOREIGN KEY (plan_id) REFERENCES plan_afiliacion (id) ON DELETE RESTRICT,
    CONSTRAINT uk_afiliacion_afiliado UNIQUE (afiliado_id)
);

CREATE TABLE afiliacion_mascota (
    afiliacion_id BIGINT NOT NULL,
    mascota_id BIGINT NOT NULL,
    CONSTRAINT pk_afiliacion_mascota PRIMARY KEY (afiliacion_id, mascota_id),
    CONSTRAINT fk_afiliacion_mascota_afiliacion
        FOREIGN KEY (afiliacion_id) REFERENCES afiliacion (id) ON DELETE CASCADE,
    CONSTRAINT fk_afiliacion_mascota_mascota
        FOREIGN KEY (mascota_id) REFERENCES mascota (id) ON DELETE CASCADE,
    CONSTRAINT uk_afiliacion_mascota_mascota UNIQUE (mascota_id)
);

CREATE TABLE bono (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    afiliado_id BIGINT NOT NULL,
    mascota_id BIGINT NOT NULL,
    servicio_id BIGINT NOT NULL,
    plan_id BIGINT NOT NULL,
    valor_base NUMERIC(14, 0) NOT NULL,
    porcentaje_descuento INTEGER NOT NULL,
    valor_pagado NUMERIC(14, 0) NOT NULL,
    fecha_compra TIMESTAMP WITH TIME ZONE NOT NULL,
    estado VARCHAR(20) NOT NULL,
    CONSTRAINT fk_bono_afiliado FOREIGN KEY (afiliado_id) REFERENCES afiliado (id) ON DELETE RESTRICT,
    CONSTRAINT fk_bono_mascota FOREIGN KEY (mascota_id) REFERENCES mascota (id) ON DELETE RESTRICT,
    CONSTRAINT fk_bono_servicio FOREIGN KEY (servicio_id) REFERENCES servicio_veterinario (id) ON DELETE RESTRICT,
    CONSTRAINT fk_bono_plan FOREIGN KEY (plan_id) REFERENCES plan_afiliacion (id) ON DELETE RESTRICT,
    CONSTRAINT ck_bono_estado CHECK (estado IN ('DISPONIBLE', 'USADO')),
    CONSTRAINT ck_bono_porcentaje CHECK (porcentaje_descuento BETWEEN 0 AND 100),
    CONSTRAINT ck_bono_valores CHECK (valor_base > 0 AND valor_pagado >= 0 AND valor_pagado <= valor_base)
);

CREATE INDEX ix_bono_afiliado_fecha ON bono (afiliado_id, fecha_compra);

CREATE TABLE prestacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mascota_id BIGINT NOT NULL,
    servicio_id BIGINT NOT NULL,
    bono_id BIGINT,
    fecha DATE NOT NULL,
    prestador VARCHAR(150) NOT NULL,
    observaciones VARCHAR(500),
    registrada_en TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_prestacion_mascota FOREIGN KEY (mascota_id) REFERENCES mascota (id) ON DELETE RESTRICT,
    CONSTRAINT fk_prestacion_servicio FOREIGN KEY (servicio_id) REFERENCES servicio_veterinario (id) ON DELETE RESTRICT,
    CONSTRAINT fk_prestacion_bono FOREIGN KEY (bono_id) REFERENCES bono (id) ON DELETE RESTRICT,
    CONSTRAINT uk_prestacion_bono UNIQUE (bono_id)
);

CREATE INDEX ix_prestacion_mascota_fecha ON prestacion (mascota_id, fecha DESC);

