-- ---------------------------------------------------------------------------------------------
-- Ley 1581 de 2012: prueba de la autorización del titular para el tratamiento de sus datos
-- (arts. 9 y 17-b). Se guarda qué versión de la política aceptó, cuándo y quién la registró.
-- ---------------------------------------------------------------------------------------------
CREATE TABLE autorizacion_datos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    afiliado_id BIGINT NOT NULL,
    version_politica VARCHAR(20) NOT NULL,
    otorgada_en TIMESTAMP WITH TIME ZONE NOT NULL,
    registrada_por VARCHAR(100) NOT NULL,
    medio VARCHAR(150) NOT NULL,
    CONSTRAINT fk_autorizacion_datos_afiliado FOREIGN KEY (afiliado_id) REFERENCES afiliado (id) ON DELETE CASCADE
);

CREATE INDEX ix_autorizacion_datos_afiliado ON autorizacion_datos (afiliado_id, otorgada_en DESC);

-- ---------------------------------------------------------------------------------------------
-- Libro de pagos: cada transacción (mensualidad o bono) con su origen, para conciliar.
-- ---------------------------------------------------------------------------------------------
ALTER TABLE cuota_plan DROP CONSTRAINT ck_cuota_plan_medio;
ALTER TABLE cuota_plan ADD CONSTRAINT ck_cuota_plan_medio
    CHECK (medio_pago IS NULL OR medio_pago IN ('EFECTIVO', 'TARJETA', 'TRANSFERENCIA', 'PSE'));

-- Un bono comprado en línea queda pendiente de pago hasta que la pasarela lo confirme.
ALTER TABLE bono DROP CONSTRAINT ck_bono_estado;
ALTER TABLE bono ADD CONSTRAINT ck_bono_estado CHECK (estado IN ('PENDIENTE_PAGO', 'DISPONIBLE', 'USADO', 'ANULADO'));

CREATE TABLE pago (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    referencia VARCHAR(30) NOT NULL,
    afiliado_id BIGINT NOT NULL,
    concepto VARCHAR(20) NOT NULL,
    cuota_id BIGINT,
    bono_id BIGINT,
    monto NUMERIC(14, 0) NOT NULL,
    -- Null solo en pagos migrados de antes del libro, cuyo medio no se registró.
    medio_pago VARCHAR(20),
    canal VARCHAR(20) NOT NULL,
    estado VARCHAR(20) NOT NULL,
    fecha_pago DATE,
    creado_en TIMESTAMP WITH TIME ZONE NOT NULL,
    confirmado_en TIMESTAMP WITH TIME ZONE,
    transaccion_pasarela VARCHAR(80),
    detalle VARCHAR(300),
    CONSTRAINT uk_pago_referencia UNIQUE (referencia),
    CONSTRAINT fk_pago_afiliado FOREIGN KEY (afiliado_id) REFERENCES afiliado (id) ON DELETE CASCADE,
    CONSTRAINT fk_pago_cuota FOREIGN KEY (cuota_id) REFERENCES cuota_plan (id) ON DELETE CASCADE,
    CONSTRAINT fk_pago_bono FOREIGN KEY (bono_id) REFERENCES bono (id) ON DELETE CASCADE,
    CONSTRAINT ck_pago_concepto CHECK (concepto IN ('CUOTA_PLAN', 'BONO')),
    CONSTRAINT ck_pago_origen CHECK (
        (concepto = 'CUOTA_PLAN' AND cuota_id IS NOT NULL AND bono_id IS NULL)
        OR (concepto = 'BONO' AND bono_id IS NOT NULL AND cuota_id IS NULL)),
    CONSTRAINT ck_pago_monto CHECK (monto >= 0),
    CONSTRAINT ck_pago_medio CHECK (medio_pago IS NULL OR medio_pago IN ('EFECTIVO', 'TARJETA', 'TRANSFERENCIA', 'PSE')),
    CONSTRAINT ck_pago_canal CHECK (canal IN ('MANUAL', 'PASARELA')),
    CONSTRAINT ck_pago_estado CHECK (estado IN ('PENDIENTE', 'APROBADO', 'RECHAZADO', 'ANULADO')),
    CONSTRAINT ck_pago_aprobado CHECK ((estado = 'APROBADO') = (fecha_pago IS NOT NULL))
);

CREATE INDEX ix_pago_afiliado ON pago (afiliado_id, creado_en DESC);
CREATE INDEX ix_pago_creado ON pago (creado_en);

-- Pagos registrados antes del libro: mensualidades pagadas y bonos comprados.
INSERT INTO pago (referencia, afiliado_id, concepto, cuota_id, monto, medio_pago, canal, estado,
                  fecha_pago, creado_en, confirmado_en, detalle)
SELECT 'PG-C' || c.id, c.afiliado_id, 'CUOTA_PLAN', c.id, c.valor, c.medio_pago, 'MANUAL', 'APROBADO',
       c.fecha_pago, COALESCE(c.pago_registrado_en, c.fecha_pago::timestamptz), c.pago_registrado_en,
       'Registrado antes del libro de pagos.'
FROM cuota_plan c
WHERE c.estado = 'PAGADA';

INSERT INTO pago (referencia, afiliado_id, concepto, bono_id, monto, medio_pago, canal, estado,
                  fecha_pago, creado_en, confirmado_en, detalle)
SELECT 'PG-B' || b.id, b.afiliado_id, 'BONO', b.id, b.valor_pagado, NULL, 'MANUAL', 'APROBADO',
       (b.fecha_compra AT TIME ZONE 'America/Bogota')::date, b.fecha_compra, b.fecha_compra,
       'Compra registrada antes del libro de pagos; el medio de pago no se registró.'
FROM bono b;
