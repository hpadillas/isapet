-- Registro de las notificaciones enviadas a los afiliados. La clave evita enviar dos veces el mismo aviso
-- (p. ej. el recordatorio de fin de periodo si la tarea programada se ejecuta de nuevo).
CREATE TABLE notificacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    afiliado_id BIGINT NOT NULL,
    tipo VARCHAR(40) NOT NULL,
    clave VARCHAR(120) NOT NULL,
    destinatario VARCHAR(254),
    asunto VARCHAR(200) NOT NULL,
    estado VARCHAR(20) NOT NULL,
    error VARCHAR(500),
    creada_en TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_notificacion_afiliado FOREIGN KEY (afiliado_id) REFERENCES afiliado (id) ON DELETE CASCADE,
    CONSTRAINT uk_notificacion_clave UNIQUE (clave),
    CONSTRAINT ck_notificacion_tipo
        CHECK (tipo IN ('BIENVENIDA', 'PLAN_ACTIVADO', 'ATENCIONES_AGOTADAS', 'FIN_PERIODO')),
    CONSTRAINT ck_notificacion_estado CHECK (estado IN ('ENVIADA', 'FALLIDA'))
);

CREATE INDEX ix_notificacion_afiliado ON notificacion (afiliado_id, creada_en DESC);
