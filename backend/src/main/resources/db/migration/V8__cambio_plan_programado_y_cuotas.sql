-- Cambio de plan programado: el plan actual sigue hasta el final de su periodo y el nuevo se activa
-- el día siguiente, con las mascotas elegidas al programarlo.
ALTER TABLE afiliacion
    ADD COLUMN plan_programado_id BIGINT,
    ADD COLUMN fecha_cambio_programado DATE,
    ADD CONSTRAINT fk_afiliacion_plan_programado
        FOREIGN KEY (plan_programado_id) REFERENCES plan_afiliacion (id) ON DELETE RESTRICT,
    ADD CONSTRAINT ck_afiliacion_cambio_programado
        CHECK ((plan_programado_id IS NULL) = (fecha_cambio_programado IS NULL));

CREATE TABLE afiliacion_mascota_programada (
    afiliacion_id BIGINT NOT NULL,
    mascota_id BIGINT NOT NULL,
    CONSTRAINT pk_afiliacion_mascota_programada PRIMARY KEY (afiliacion_id, mascota_id),
    CONSTRAINT fk_afiliacion_mascota_programada_afiliacion
        FOREIGN KEY (afiliacion_id) REFERENCES afiliacion (id) ON DELETE CASCADE,
    CONSTRAINT fk_afiliacion_mascota_programada_mascota
        FOREIGN KEY (mascota_id) REFERENCES mascota (id) ON DELETE CASCADE
);

-- Cuota mensual del plan: una por periodo de afiliación. Nace pendiente y el administrador registra el pago.
CREATE TABLE cuota_plan (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    afiliado_id BIGINT NOT NULL,
    plan_id BIGINT NOT NULL,
    periodo_desde DATE NOT NULL,
    periodo_hasta DATE NOT NULL,
    valor NUMERIC(14, 0) NOT NULL,
    estado VARCHAR(20) NOT NULL,
    fecha_pago DATE,
    medio_pago VARCHAR(20),
    pago_registrado_en TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_cuota_plan_afiliado FOREIGN KEY (afiliado_id) REFERENCES afiliado (id) ON DELETE CASCADE,
    CONSTRAINT fk_cuota_plan_plan FOREIGN KEY (plan_id) REFERENCES plan_afiliacion (id) ON DELETE RESTRICT,
    CONSTRAINT uk_cuota_plan_periodo UNIQUE (afiliado_id, periodo_desde),
    CONSTRAINT ck_cuota_plan_periodo CHECK (periodo_hasta >= periodo_desde),
    CONSTRAINT ck_cuota_plan_valor CHECK (valor > 0),
    CONSTRAINT ck_cuota_plan_estado CHECK (estado IN ('PENDIENTE', 'PAGADA')),
    CONSTRAINT ck_cuota_plan_medio CHECK (medio_pago IS NULL OR medio_pago IN ('EFECTIVO', 'TARJETA', 'TRANSFERENCIA')),
    CONSTRAINT ck_cuota_plan_pago
        CHECK ((estado = 'PAGADA') = (fecha_pago IS NOT NULL AND medio_pago IS NOT NULL))
);
